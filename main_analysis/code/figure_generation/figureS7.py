import gc
import numpy as np
import pandas as pd
import matplotlib as mpl
import matplotlib.pyplot as plt
from matplotlib import font_manager
from joblib import load

from pathlib import Path

# ==========================================================================
# All paths are resolved relative to the repository root.
THIS_FILE = Path(__file__).resolve()
PROJECT_ROOT = THIS_FILE.parents[3]

OUTPUTS   = PROJECT_ROOT / "main_analysis" / "Outputs"
DIR_SIMS  = OUTPUTS / "simulations"
DIR_OPT   = OUTPUTS / "optimisation"
DIR_DISTR = PROJECT_ROOT / "main_analysis" / "host_distributions"
DIR_OUT   = OUTPUTS / "figures"
# ==========================================================================

SIM_DIR    = DIR_SIMS
DIR_METRIC = DIR_OPT / "output_metric_sfreq52_nsite10"
DIR_CONFIG = DIR_OPT / "output_config"
OUT_DIR    = DIR_OUT

OUT_CSV = os.path.join(OUT_DIR, "FigureS7_variance_bootstrap.csv")
OUT_PNG = os.path.join(OUT_DIR, "FigureS7.png")

N_TRACE_CONFIGS = 30      # configurations sampled along each SA trace
N_NEIGHBOURS = 20         # single-swap neighbours of each optimum
N_BOOT = 1000             # bootstrap resamples
SEED = 0
# ==========================================================================

SURVEY_FREQ = 52
NSITES = 10
NTREES_SURVEY = 30
P_DETECT = 0.75
SIGMA0 = 0.01
LOGISTIC_RATE = 0.1693

AREAS = [f"{i:02d}" for i in range(1, 9)]
ROADS = ([f"01_{i}" for i in range(5)] + [f"02_{i}" for i in range(3)] +
         [f"03_{i}" for i in range(6)] + [f"05_{i}" for i in range(3)])

OUT_DIR.mkdir(parents=True, exist_ok=True)
rng = np.random.default_rng(SEED)


