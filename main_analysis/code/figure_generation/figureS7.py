"""
VARIANCE DECOMPOSITION AND BOOTSTRAP RANK STABILITY (Reviewer 1, comment 6)

Uses the stored simulations and optimisation outputs at baseline
(N = 10 sites, F = 52 weeks) for all 144 study areas (136 accessibility-
constrained plus 8 unconstrained). No new optimisation is run.

(a) Variance decomposition
    For each study area, ~30 configurations are sampled along the simulated
    annealing trace, from early to late. Each configuration's objective is
    estimated as the mean of its per-simulation detection probabilities.
    The variance of these estimates across configurations is split into:
        Monte Carlo variance  = mean over configs of Var_s(P_s) / M
        genuine variance      = observed variance - Monte Carlo variance
    The fraction attributable to genuine differences between configurations
    is reported.

(b) Near-optimal neighbourhood
    For the optimal configuration, 20 neighbours are generated by swapping
    one site for another accessible cell. For each neighbour:
      - the paired difference (optimum minus neighbour) is computed over the
        same 2,000 simulations, with its standard error and z-score
      - the simulations are bootstrap-resampled 1,000 times, and the
        proportion of resamples in which the optimum remains best is recorded

Detection applies to symptomatic plants only, as in the corrected analysis.

    python variance_bootstrap.py
"""

